/**
 * Renders docs/reference/compatibility.md from the matrix data (`compat.json`) and the miniapp CHANGELOG. The page is
 * generated: `pnpm --filter compat generate` writes it, and `test/matrix.test.mjs` fails when it differs.
 */
import semver from 'semver';

const OWNER = 'zoyoong124@gmail.com';
const UPDATED = '2026-11-16';
const WORKSPACE = 'workspace';

/**
 * Which CHANGELOG entry names a non-ok scenario. `needle` is a phrase of the line that states the break, found in the
 * section of `version`. A published page with a non-ok cell that no rule names fails the matrix test.
 */
export const BREAKS = [
  { applies: (page) => page !== WORKSPACE && semver.lt(page, '0.2.0'), version: '0.2.0', needle: 'Breaking: the v1 message types' },
  { applies: (_page, s) => s.id === 'share' && s.status === 'fallback', version: '0.3.0', needle: 'Add `share.open`' },
  { applies: (_page, s) => s.id === 'game-handshake', version: '0.4.0', needle: 'Add the `game.*` namespace' },
  { applies: (_page, s) => s.id === 'game-late-host', version: '0.4.1', needle: 'no longer leaves the page dead' },
];

/** The CHANGELOG line that names the break of `scenario` on `page`, or `null` when no rule matches. */
export function changelogEntry(changelog, page, scenario) {
  const rule = BREAKS.find((r) => r.applies(page, scenario));
  if (rule === undefined) return null;
  const start = changelog.indexOf(`\n## ${rule.version}\n`);
  if (start < 0) throw new Error(`the CHANGELOG has no section for ${rule.version}`);
  const next = changelog.indexOf('\n## ', start + 1);
  const section = changelog.slice(start, next < 0 ? undefined : next);
  const line = section.split('\n').find((l) => l.includes(rule.needle));
  if (line === undefined) throw new Error(`the ${rule.version} CHANGELOG section no longer holds "${rule.needle}", so update BREAKS in render.mjs`);
  return { version: rule.version, text: line.replace(/^- [0-9a-f]{7}: /, '').trim() };
}

const cellText = (text) => text.split('|').join('\\|');
const code = (text) => `\`${text}\``;
const table = (header, rows) => [`| ${header.join(' | ')} |`, `| ${header.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cellText).join(' | ')} |`)].join('\n');
const LABEL = { ok: 'ok', fallback: 'fb', gap: 'gap', broken: 'FAIL', 'n/a': 'n/a' };
const firstSentence = (text) => {
  const end = text.indexOf('. ');
  return end < 0 ? text : text.slice(0, end + 1);
};
// WHY: the docs site rewrites a dot in a link fragment to a dash, so an id with a dot would match on GitHub only.
const slug = (text) => text.replaceAll('.', '-');
const anchor = (build, page, host) => slug(`${build}-page-${page}-host-${host}`);
const lateAnchor = (page) => slug(`late-page-${page}`);

export function renderPage(compat, changelog) {
  const { pages, hosts } = compat.meta;
  const published = pages.filter((p) => p !== WORKSPACE);

  const label = (version) => (compat.versions[version].release === undefined ? version : `[${version}]`);
  const header = (first) => [first, ...hosts.map(label)];

  const sameEvidence = (page, host) => JSON.stringify(compat.cells.esm[page][host]) === JSON.stringify(compat.cells.global[page][host]);
  const homeOf = (build, page, host) => {
    if (build === 'global' && sameEvidence(page, host)) return anchor('esm', page, host);
    return anchor(build, page, host);
  };
  const cellLink = (build, page, host) => {
    const cell = compat.cells[build][page][host];
    return cell.scenarios === undefined ? cell.verdict : `[${cell.verdict}](#${homeOf(build, page, host)})`;
  };
  const grid = (build) => table(header('page \\ host'), pages.map((page) => [`**${label(page)}**`, ...hosts.map((host) => cellLink(build, page, host))]));

  const out = [];
  out.push(
    '---',
    'title: SDK Compatibility',
    'type: reference',
    'status: accepted',
    `owner: ${OWNER}`,
    `last-updated: ${UPDATED}`,
    'audience: public',
    '---',
    '',
    '# SDK compatibility',
    '',
    '> Which `@skkuverse/miniapp` page version works with which host version, measured from the published packages and the workspace, with a link to the release tag of each version. For anyone deciding whether a page built on one SDK runs in an app built on another.',
    '',
    '<!-- This page is generated by packages/compat. Run `pnpm --filter compat generate` to rewrite it, and never edit it by hand. -->',
    '',
    '## Overview',
    '',
    'A page and the app that hosts it each carry a copy of the SDK, and the two copies agree on a protocol in `@skkuverse/miniapp/protocol`. The page is the SDK its author built with. The host of version H is what an app built with H does: the bootstrap script it injects, the parser it runs on every message, and the methods it grants. Each cell of the tables below runs the page of one version against the host of another, in a fresh happy-dom window, and judges what the host received. `packages/compat/compat.json` holds the same data for a program to read, shaped like MDN browser-compat-data.',
    '',
    'The cheap, deterministic part is measured here. The native handlers, the real web view and the app\'s own dispatcher are not, and a green cell means the host parsed, granted and routed the message, not that the phone then did the right thing.',
    '',
    '- `ok`: every scenario passed.',
    '- `fb`: the host does not grant a method and the page degraded gracefully.',
    '- `gap`: the host predates the feature, so the page reports no host.',
    '- `FAIL`: the host dropped what the page sent, or the page sent nothing though the host grants it.',
    '- `n/a`: not computable.',
    '',
    'Each non-ok cell links to its entry under [Non-ok cells](#non-ok-cells), with the scenario, the wire message, the host\'s verdict, a command that reruns the cell, and the CHANGELOG entry that names the break.',
    '',
    '## Versions',
    '',
    'Each published version links to the GitHub Release of the tag that release pushed. A version with no commit that rebuilds its tarball byte for byte reads "no reproducible commit".',
    '',
  );
  out.push(
    table(
      ['Version', 'Release tag', 'Commit'],
      pages.map((page) => {
        const v = compat.versions[page];
        if (page === WORKSPACE) return ['workspace', 'unpublished', 'the package in this repository'];
        if (v.release === undefined) return [page, v.reason, '-'];
        const sha = v.commit.slice(0, 7);
        return [page, `[${v.tag}](${v.release})`, `\`${sha}\``];
      }),
    ),
    '',
  );
  const unmeasured = Object.entries(compat.meta.unmeasured);
  if (unmeasured.length > 0) out.push(...unmeasured.map(([version, why]) => `Host ${version} is not a column of any verdict: ${why}.`), '');

  out.push(
    '## Page by host',
    '',
    'Rows are the page SDK and columns are the host bootstrap. Both load the ES module build.',
    '',
    grid('esm'),
    '',
    '### Script-tag build',
    '',
    'The same table with the page loaded from `dist/miniapp-sdk.global.js`. That build has no `./game` entry, so a game row reads as a mini-app page.',
    '',
    grid('global'),
    '',
    '## Late host',
    '',
    'The host appears after the page gave up waiting. The result belongs to the page, so a version reads the same on every host that grants `game.*`. A `gap` is a host with no `game.*` grant, the cell the [first table](#page-by-host) already links.',
    '',
    table(
      ['page \\ host', ...hosts.map(label)],
      Object.entries(compat.late).map(([page, row]) => [
        `**${label(page)}**`,
        ...hosts.map((h) => (['ok', 'n/a', 'gap'].includes(row[h].status) ? row[h].status : `[${LABEL[row[h].status]}](#${lateAnchor(page)})`)),
      ]),
    ),
    '',
    '## Host bootstrap alone',
    '',
    table(
      ['host', 'install', 'reinject', 'origin gate', 'subframe gate', 'receive', 'script, no origin', 'script, with origin', 'deliver script'],
      hosts.map((host) => {
        const h = compat.hosts[host];
        const b = h.bootstrap;
        const s = h.script;
        return [
          `**${label(host)}**`,
          ...['host-install', 'host-reinject', 'host-origin-gate', 'host-subframe-gate', 'host-receive'].map((id) => (b === null ? 'n/a' : b[id])),
          ...(s === null ? ['n/a', 'n/a', 'n/a'] : [code(s.noOrigin), code(s.withOrigin), code(s.deliver)]),
        ];
      }),
    ),
    '',
    'The three script columns are a hash of what `hostBootstrapScript` and `hostDeliverScript` produce, so a release that changes what an app injects shows as a new hash.',
    '',
    '## Features',
    '',
    'Each feature is a scenario, and `compat.json` records, per page version, the first host version where it works, shaped like MDN browser-compat-data. `partial` means a host before that version still runs the page through a fallback.',
    '',
    table(
      ['Feature', ...published.map(label), 'workspace'],
      Object.entries(compat.features).map(([name, { __compat: f }]) => [
        code(name),
        ...pages.map((page) => {
          const s = f.support[page];
          if (s.version_added === false) return 'never';
          const range = s.version_removed === undefined ? `host ${s.version_added}+` : `host ${s.version_added}, removed at ${s.version_removed}`;
          return s.partial_implementation ? `${range}, partial` : range;
        }),
      ]),
    ),
    '',
    '## Non-ok cells',
    '',
  );

  const homes = [];
  for (const build of ['esm', 'global']) {
    for (const page of pages) {
      for (const host of hosts) {
        const cell = compat.cells[build][page][host];
        if (cell.scenarios !== undefined && homeOf(build, page, host) === anchor(build, page, host)) homes.push({ build, page, host, cell });
      }
    }
  }
  if (homes.length === 0) out.push('Every measured cell is `ok`.', '');
  for (const { build, page, host, cell } of homes) {
    const suffix = build === 'global' ? ' (script-tag build)' : '';
    const modes = [...new Set(cell.scenarios.map((s) => s.mode))];
    const builds = build === 'esm' && sameEvidence(page, host) ? ['esm', 'global'] : [build];
    const reruns = modes.flatMap((mode) => builds.map((b) => code(`pnpm --filter compat exec node src/cell.mjs ${mode} ${page} ${host}${b === 'global' ? ' global' : ''}`)));
    out.push(`<a id="${anchor(build, page, host)}"></a>`, '', `### Page ${page} on host ${host}${suffix}`, '', `Verdict ${code(cell.verdict)}${builds.length === 2 ? ' in both builds' : ''}. Rerun it with ${reruns.join(' and ')}.`, '');
    const named = new Map();
    for (const s of cell.scenarios) {
      const wire = s.observed === undefined || s.observed.length === 0 ? 'none' : s.observed.map(code).join(', ');
      out.push(`- **${s.id}** (${LABEL[s.status]}). Wire message: ${wire}. Host: ${s.detail}.`);
      const entry = changelogEntry(changelog, page, s);
      named.set(entry === null ? 'none' : `${entry.version}: ${firstSentence(entry.text)}`, entry);
    }
    out.push('');
    for (const key of named.keys()) out.push(key === 'none' ? 'No CHANGELOG entry names this.' : `CHANGELOG ${key}`, '');
    out.push('');
  }
  for (const [page, row] of Object.entries(compat.late)) {
    const bad = hosts.filter((h) => !['ok', 'n/a', 'gap'].includes(row[h].status));
    if (bad.length === 0) continue;
    out.push(`<a id="${lateAnchor(page)}"></a>`, '', `### Page ${page}, late host`, '', `Rerun a cell with ${code(`pnpm --filter compat exec node src/cell.mjs late ${page} <host>`)}.`, '');
    const groups = new Map();
    for (const h of bad) {
      const key = `${row[h].status}|${row[h].detail}`;
      groups.set(key, [...(groups.get(key) ?? []), h]);
    }
    const named = new Set();
    for (const [key, list] of groups) {
      const [status, detail] = [key.slice(0, key.indexOf('|')), key.slice(key.indexOf('|') + 1)];
      out.push(`- **game-late-host** (${LABEL[status]}) on host ${list.join(', ')}. Wire message: none. Host: ${detail}.`);
      const entry = changelogEntry(changelog, page, { id: 'game-late-host', status });
      named.add(entry === null ? 'none' : `${entry.version}: ${firstSentence(entry.text)}`);
    }
    out.push('');
    for (const key of named) out.push(key === 'none' ? 'No CHANGELOG entry names this.' : `CHANGELOG ${key}`, '');
  }
  const defs = Object.entries(compat.versions).filter(([, v]) => v.release !== undefined);
  out.push('<!-- Release links -->', '', ...defs.map(([version, v]) => `[${version}]: ${v.release}`), '');
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}
